CREATE DATABASE IF NOT EXISTS proyectomanejo
  DEFAULT CHARACTER SET utf8mb4
  DEFAULT COLLATE utf8mb4_unicode_ci;
USE proyectomanejo;

SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

-- --------------------
-- Catálogos base
-- --------------------

-- 1. Tablas de Catálogo y Referencia (Raíz)
CREATE TABLE IF NOT EXISTS TIPOS_CARRERA (
  ID_CARRERA TINYINT PRIMARY KEY AUTO_INCREMENT,
  NOMBRE_CARRERA VARCHAR(80) UNIQUE NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS ROLES (
  ID_ROL INT PRIMARY KEY AUTO_INCREMENT,
  NOM_ROL VARCHAR(100) NOT NULL,
  DES_ROL TEXT,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS TIPOS_EVENTO (
  ID_TIPO_EVE INT PRIMARY KEY AUTO_INCREMENT,
  NOM_TIPO_EVE VARCHAR(100) UNIQUE NOT NULL,
  DES_TIPO_EVE TEXT,
  IMG_TIPO_EVE VARCHAR(255),
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

